-- =============================================================================
-- practice-schema.sql — "TixHub" event-ticketing practice database
-- Target: PostgreSQL 16. Used by every file in 04-sql-databases/ and by
-- sql-practice.md. Safe to re-run: it drops and recreates everything.
--
-- Load it:
--   createdb tixhub
--   psql -d tixhub -f practice-schema.sql
--
-- Or with Docker:
--   docker run --name pg -e POSTGRES_PASSWORD=pg -p 5432:5432 -d postgres:16
--   docker cp practice-schema.sql pg:/tmp/ && \
--   docker exec -it pg psql -U postgres -c 'CREATE DATABASE tixhub'
--   docker exec -it pg psql -U postgres -d tixhub -f /tmp/practice-schema.sql
--
-- Tables (8):
--   employees    staff with a self-referencing manager_id (hierarchies, salaries)
--   customers    buyers, with self-referencing referred_by
--   venues       places events happen
--   events       things you can buy tickets for (N:1 venue)
--   orders       a customer's checkout (N:1 customer)
--   order_items  junction table orders <-> events (M:N) with quantity + price
--   payments     payment attempts per order (1:N), includes a deliberate double charge
--   page_views   200,000 generated rows so EXPLAIN plans are meaningful
--
-- Deliberate "flaws" you will find and fix in the exercises:
--   * customers 1 and 10 have the same e-mail ignoring case (unique is case-sensitive)
--   * order 7 was charged twice (duplicate SUCCEEDED payment)
--   * order 20 is PAID but has no successful payment
--   * order ids 12 and 17 are missing (gaps)
--   * NO index on page_views(event_id), page_views(customer_id), orders(customer_id),
--     order_items(event_id) — foreign keys do NOT get indexes automatically in Postgres.
-- =============================================================================

DROP TABLE IF EXISTS page_views, payments, order_items, orders, events, venues,
                     customers, employees CASCADE;

