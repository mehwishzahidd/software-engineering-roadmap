-- -----------------------------------------------------------------------------
-- page_views: bulk, generated data (200,000 rows) for EXPLAIN / index practice.
-- setseed() makes random() deterministic, so everyone gets the same data.
-- ~70% of views are anonymous (customer_id IS NULL).
-- Event 9 ("Data Summit") is deliberately "hot" (~40% of all views).
-- -----------------------------------------------------------------------------
CREATE TABLE page_views (
    id           bigint       GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    event_id     integer      NOT NULL REFERENCES events (id),
    customer_id  integer      REFERENCES customers (id),
    device       text         NOT NULL CHECK (device IN ('web', 'ios', 'android')),
    viewed_at    timestamptz  NOT NULL
);

SELECT setseed(0.42);

INSERT INTO page_views (event_id, customer_id, device, viewed_at)
SELECT
    CASE WHEN r1 < 0.40 THEN 9                       -- hot event
         ELSE 1 + floor(r2 * 10)::int END,           -- uniform 1..10
    CASE WHEN r3 < 0.70 THEN NULL
         ELSE 1 + floor(r4 * 12)::int END,           -- customers 1..12
    (ARRAY['web', 'ios', 'android'])[1 + floor(r5 * 3)::int],
    timestamptz '2026-01-01 00:00+00' + (r6 * interval '180 days')
FROM (
    SELECT random() AS r1, random() AS r2, random() AS r3,
           random() AS r4, random() AS r5, random() AS r6
    FROM generate_series(1, 200000)
) AS g;

-- -----------------------------------------------------------------------------
-- Identity columns: we inserted explicit ids, so move the sequences past them,
-- otherwise the next INSERT without an id fails with a duplicate-key error.
-- -----------------------------------------------------------------------------
SELECT setval(pg_get_serial_sequence('customers', 'id'), (SELECT max(id) FROM customers));
SELECT setval(pg_get_serial_sequence('venues',    'id'), (SELECT max(id) FROM venues));
SELECT setval(pg_get_serial_sequence('events',    'id'), (SELECT max(id) FROM events));
SELECT setval(pg_get_serial_sequence('orders',    'id'), (SELECT max(id) FROM orders));
SELECT setval(pg_get_serial_sequence('payments',  'id'), (SELECT max(id) FROM payments));

